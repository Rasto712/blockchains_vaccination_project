# a stand-in ABI per contract: FakeNode's contracts have none, and the real artifacts are git ignored
ABIS = {
    name: [
        {"type": "function", "name": "view", "inputs": [], "outputs": [], "stateMutability": "view"},
        {"type": "error", "name": f"{name}Error", "inputs": []},
    ]
    for name in chain.CONTRACT_NAMES
}
POLICY = ("default-src 'self'; connect-src 'self' http://127.0.0.1:8545; frame-ancestors 'none'; base-uri 'none'; "
          "form-action 'self'")
BUNDLE_HEADER = "// generated by npm run build:ui, do not edit"
ENTRY = server.STATIC_DIR / "src" / "viem.js"
CHAIN_JS = server.STATIC_DIR / "chain.js"
VIEWS = ("get_user_info", "get_consent", "get_reward_balance", "list_access_events")


class ViemTestCase(UITestCase):
    def setUp(self):
        super().setUp()
        for name, contract in self.fake.contracts.items():
            contract.abi = ABIS[name]

    def identity_hash(self, role, status=200):
        return self.call("GET", f"/api/identity-hash?role={role}", status=status)

    def called(self):
        return {name for name, _ in self.fake.calls}


class ContractsTests(ViemTestCase):
    def test_addresses_and_abis_only_after_the_checks(self):
        self.ready()
        answer = self.call("GET", "/api/contracts")
        self.assertEqual(answer["status"], "ok")
        details = answer["details"]
        self.assertEqual(details["contracts"], {
            name: {"address": self.fake.contracts[name].address, "abi": ABIS[name]} for name in chain.CONTRACT_NAMES
        })
        self.assertEqual(details["accounts"], self.fake.addresses)
        self.assertEqual((details["chain_id"], details["rpc_url"]), (31337, "http://127.0.0.1:8545"))
        self.assertEqual(details["scopes"], {"MEASLES_STATUS": 1, "VACCINATION_SCHEDULE": 2})
        self.assertEqual(details["reasons"], {reason.name: int(reason) for reason in Reason})
        # every contract went through load_contract's checks; nothing was sent or read from the contracts
        self.assertEqual([call["name"] for call in self.fake.calls_to("load_contract")], list(chain.CONTRACT_NAMES))
        self.assertEqual(self.called(), {"connect", "select_account", "load_contract"})

    def test_a_missing_or_stale_deployment_serves_nothing(self):
        for failure in (DeploymentUnavailable("deployment unavailable"),
                        DeploymentUnavailable("deployment is from another run of the node"),
                        DeploymentUnavailable("contract code does not match the deployment")):
            self.fake.failures["load_contract"] = failure
            answer = self.call("GET", "/api/contracts")
            self.assertEqual((answer["status"], answer["message"]), ("unavailable", NO_DEPLOYMENT))
            self.assertEqual(answer["details"], {})

    def test_node_down_and_missing_artifacts_keep_their_messages(self):
        self.fake.failures["connect"] = ChainUnavailable("RPC connection failed")
        self.assertEqual(self.call("GET", "/api/contracts")["message"], NODE_DOWN)
        # the message names a path, which must not reach the page
        self.fake.failures["load_contract"] = ArtifactUnavailable("/Users/somebody/artifacts")
        answer = self.call("GET", "/api/contracts")
        self.assertEqual((answer["message"], answer["details"]), (NO_ARTIFACTS, {}))

    def test_a_node_that_stops_midway_serves_nothing(self):
        self.fake.failures["select_account"] = ChainUnavailable("RPC request failed")
        answer = self.call("GET", "/api/contracts")
        self.assertEqual((answer["message"], answer["details"]), (NODE_DOWN, {}))

    def test_another_host_is_refused_before_any_chain_call(self):
        status, _, body = self.request("GET", "/api/contracts", headers={"Host": f"evil.example:{self.port}"})
        self.assertEqual(status, 403)
        self.assertNotIn(b"abi", body)
        self.assertEqual(self.fake.calls, [])


class IdentityHashTests(ViemTestCase):
    def test_each_registering_role_gets_its_salted_hash_only(self):
        self.ready()
        for label in records.REGISTERING_LABELS:
            answer = self.identity_hash(label)
            expected = records.prepare_identity(*records.identity_paths(self.settings, label))
            self.assertEqual(answer["status"], "ok")
            self.assertEqual(answer["details"], {"identity_hash": f"0x{expected.hex()}"})
        # hashing needs no node
        self.assertEqual(self.fake.calls, [])

    def test_other_roles_are_refused(self):
        self.ready()
        for role in ("deployer", "clinic"):
            answer = self.identity_hash(role, status=400)
            self.assertEqual((answer["status"], answer["message"]), ("invalid", "only guardian, school and doctor register"))
        for path in ("/api/identity-hash?role=teacher", "/api/identity-hash?role=", "/api/identity-hash"):
            answer = self.call("GET", path, status=400)
            self.assertEqual((answer["status"], answer["message"]), ("invalid", "unknown role"))

    def test_missing_files_are_unavailable_without_a_path(self):
        self.assertEqual(self.identity_hash("guardian")["message"], "unavailable: identity unavailable")
        self.ready()
        Path(records.identity_paths(self.settings, "school")[1]).unlink()
        self.assertEqual(self.identity_hash("school")["message"], "unavailable: salt unavailable")


