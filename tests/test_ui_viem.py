class PolicyTests(ViemTestCase):
    def test_every_response_allows_connections_to_the_node_only(self):
        for method, path, headers in (
            ("GET", "/", {}), ("GET", "/api/state", {}), ("GET", "/static/vendor/viem.js", {}), ("GET", "/api/contracts", {}),
            ("GET", "/api/identity-hash?role=deployer", {}), ("GET", "/nothing", {}), ("PUT", "/api/setup", {}),
            ("GET", "/api/state", {"Host": "evil.example"}), ("POST", "/api/setup", {"Origin": "http://evil.example"}),
        ):
            _, sent, _ = self.request(method, path, {} if method == "POST" else None, headers)
            self.assertEqual(sent["content-security-policy"], POLICY, (method, path))
            for name, value in server.SECURITY_HEADERS:
                self.assertEqual(sent[name.lower()], value, (method, path, name))

    def test_only_a_plain_http_url_names_its_origin(self):
        for url, origin in (
            ("http://127.0.0.1:8545", "http://127.0.0.1:8545"), ("http://localhost:8545/", "http://localhost:8545"),
            ("HTTP://LOCALHOST:8545", "http://localhost:8545"), ("https://node.example:443/rpc", "https://node.example:443"),
            ("http://127.0.0.1", "http://127.0.0.1"),
        ):
            self.assertEqual(server.rpc_origin(url), origin, url)
        for url in (
            None, 42, "", "ws://127.0.0.1:8545", "http://user:pw@127.0.0.1:8545", "http://user@127.0.0.1:8545",
            "http://[::1]:8545", "http://例.jp:8545", "http://x;script-src *:8545", "http://127.0.0.1:8545;script-src *",
            "http://127.0.0.1:8545\r\nX-Evil: 1", "http://'x':8545", "http://a b:8545", "http://127.0.0.1:99999",
            "http:///rpc",
        ):
            self.assertIsNone(server.rpc_origin(url), url)
        self.assertEqual(
            server.content_security_policy(None),
            "default-src 'self'; connect-src 'self'; frame-ancestors 'none'; base-uri 'none'; form-action 'self'",
        )

    def test_a_bad_or_missing_rpc_url_leaves_the_page_no_way_to_the_node(self):
        for settings in (dict(self.settings, rpc_url="http://user:pw@127.0.0.1:8545"), {
            key: value for key, value in self.settings.items() if key != "rpc_url"
        }):
            other = server.UIServer(settings, self.settings_file, port=0)
            self.addCleanup(other.server_close)
            self.assertEqual((other.rpc_origin, other.rpc_url), (None, ""))
            self.assertNotIn("8545", other.csp)
        # the page gets the URL rebuilt from its checked parts, never the setting as written
        other = server.UIServer(dict(self.settings, rpc_url=" http://127.0.0.1:8545/rpc"), self.settings_file, port=0)
        self.addCleanup(other.server_close)
        self.assertEqual(other.rpc_url, "http://127.0.0.1:8545/rpc")


class PageFileTests(ViemTestCase):
    def test_the_prebuilt_bundle_is_served_with_its_header(self):
        status, headers, body = self.request("GET", "/static/vendor/viem.js")
        self.assertEqual(status, 200)
        self.assertEqual(headers["content-type"], "text/javascript; charset=utf-8")
        self.assertEqual(body.decode().splitlines()[0], BUNDLE_HEADER)
        self.assertIn(b"var Viem=", body)
        # the entry and the folders are not pages
        for path in ("/static/src/viem.js", "/static/vendor/", "/static/vendor/viem.js.map", "/static/src/"):
            self.assertEqual(self.request("GET", path)[0], 404, path)

    def test_the_page_loads_viem_first(self):
        page = (server.STATIC_DIR / "index.html").read_text()
        scripts = re.findall(r'<script src="/static/([^"]+)" defer></script>', page)
        self.assertEqual(scripts, ["vendor/viem.js", "chain.js", "app.js", "demo.js"])

    def test_everything_chain_js_takes_from_viem_is_in_the_bundle(self):
        used = set(re.findall(r"\bViem\.(\w+)", CHAIN_JS.read_text()))
        entry = ENTRY.read_text()
        exported = {name.strip() for block in re.findall(r"export \{([^}]*)\}", entry) for name in block.split(",")} - {""}
        bundle = (server.STATIC_DIR / "vendor" / "viem.js").read_text()
        self.assertTrue(used)
        self.assertLessEqual(used, exported)
        for name in exported:
            self.assertRegex(bundle, rf"\b{name}:\(\)=>", name)
        self.assertIn("viem (https://viem.sh) - MIT License", bundle)

    def test_chain_js_shows_the_console_texts(self):
        text = CHAIN_JS.read_text()
        self.assertIn(f"'{actions.NODE_UNAVAILABLE_MESSAGE}'", text)
        for part in ("`rejected: ${", "'pending: not confirmed'", "`failed: ${", "'rejected: Reverted'"):
            self.assertIn(part, text)
        # the page asks for the lean snapshot and reads the contract views itself
        self.assertIn("/api/state?chain_views=0", (server.STATIC_DIR / "app.js").read_text())


